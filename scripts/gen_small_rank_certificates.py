#!/usr/bin/env python3
"""Usage: python3 scripts/gen_small_rank_certificates.py P0 Goldbach/WilliamsonSmallRanksData.lean

Generate Goldbach/WilliamsonSmallRanksData.lean (row-split certificates) for prime ranks 5 <= P < P0.

The enumeration order reproduces `candsAt` in Goldbach/WilliamsonSmallRanks.lean exactly:
for each row ℓ, divisors d of prodF fs in `divsF` order, N = ℓ + d filtered by `prcB`.
Each witness (i, r): i ∈ I, r prime, P ≤ r, r ∣ N - i."""
import sys
from math import lcm
from functools import reduce
P0=int(sys.argv[1]); out=sys.argv[2]
def primes(n):
    s=bytearray([1])*(n+1); s[0]=s[1]=0
    for i in range(2,int(n**.5)+1):
        if s[i]: s[i*i::i]=bytearray(len(s[i*i::i]))
    return [i for i in range(n+1) if s[i]]
PS=primes(100000)
def idx(P): return [q for q in PS if 3<=q<=P]
def info(P):
    p=max(q for q in PS if q<P)
    m=(P-3)//2
    B=reduce(lcm, range(1,m+1)) if m>=1 else 1
    x=B; a=0
    while x%2==0: x//=2; a+=1
    fs=[]
    for r in PS:
        if r==2: continue
        if x==1: break
        e=0
        while x%r==0: x//=r; e+=1
        if e: fs.append((r,e))
    return p,B,a,fs
def divs(fs):
    if not fs: return [1]
    (r,e),rest=fs[0],fs[1:]
    R=divs(rest)
    return [r**k*d for k in range(e+1) for d in R]
def witness(P,N,I):
    for r in PS:
        if r<P: continue
        for i in I:
            if (N-i)%r==0: return (i,r)
    raise Exception("no witness")
ranks=[q for q in PS if 5<=q<P0]
L=["import Goldbach.WilliamsonSmallRanks\n",
   f"/-! # Certified elimination of the prime ranks `5 ≤ P < {P0}`\n",
   "Generated by `scripts/gen_small_rank_certificates.py`. For each rank `P` and row `ℓ`, the",
   "candidate heights `N = ℓ + d` (`d ∣ prodF fs`, first-failure conditions) are listed by",
   "`candsAt`, and each one is killed by a witness `(i, r)`: `r ≥ P` prime with `r ∣ N - i`.",
   "The kernel checks every witness and the completeness of the enumeration (`rank_clear_rows`).",
   "No native code evaluation is used (`decide +kernel` only). -/\n",
   "namespace WilliamsonMurII\n",
   "set_option maxRecDepth 100000\n"]
tot=0
for P in ranks:
    p,B,a,fs=info(P); I=idx(P); ip=idx(p); D=divs(fs); res={j%p for j in ip}
    fsl="["+", ".join(f"({r}, {e})" for r,e in fs)+"]"
    L.append(f"/-- Rank {P}: previous prime {p}; `deficitBudget {P} 1 = 2^{a} * prodF fs{P}`. -/")
    L.append(f"def fs{P} : List (ℕ × ℕ) := {fsl}\n")
    rowsP=[]
    for l in I:
        C=[l+d for d in D if P<l+d and (l+d)%2==0 and 3*p+3<=l+d and (l+d)%p in res]
        W=[witness(P,N,I) for N in C]; tot+=len(C)
        body="[" + ", ".join(f"({i}, {r})" for i,r in W) + "]"
        L.append(f"def w{P}_{l} : List (ℕ × ℕ) := {body}")
        L.append(f"theorem c{P}_{l} : checkCert {P} (candsAt {P} {p} fs{P} {l}) w{P}_{l} = true := by decide +kernel\n")
        rowsP.append(l)
    arms="\n".join(f"  | {l} => w{P}_{l}" for l in rowsP)
    L.append(f"/-- Row certificates of rank {P}. -/\ndef cert{P} : ℕ → List (ℕ × ℕ)\n{arms}\n  | _ => []\n")
    rc=" | ".join("rfl" for _ in rowsP)
    ex=", ".join(f"c{P}_{l}" for l in rowsP)
    L.append(f"""theorem idx{P} : idxList {P} = [{", ".join(map(str,rowsP))}] := by decide +kernel

theorem rank{P}_clear : ∀ p' N, PreviousRankConditions p' {P} N → ¬ BadFamily {P} N := by
  refine rank_clear_rows (p := {p}) (a := {a}) (fs := fs{P}) cert{P}
    (by decide +kernel) (by norm_num) (by decide +kernel) (by decide +kernel)
    (by decide +kernel) ?_
  intro ℓ hℓ
  rw [idx{P}] at hℓ
  simp only [List.mem_cons, List.not_mem_nil, or_false] at hℓ
  rcases hℓ with {rc}
  exacts [{ex}]
""")
names=" | ".join(f"exact rank{P}_clear p N hprc" for P in ranks)
L.append(f"""/-- **Small ranks, certified.** No bad family of prime rank `5 ≤ P < {P0}` satisfies the
    previous-rank conditions ({tot} candidate heights, each killed by a kernel-checked witness). -/
theorem small_ranks_clear : ∀ P p N, Nat.Prime P → 5 ≤ P → P < {P0} →
    PreviousRankConditions p P N → ¬ BadFamily P N := by
  intro P p N hP h5 hlt hprc
  interval_cases P <;> first | {names} | exact absurd hP (by norm_num)

/-- **Goldbach from the two walls at threshold {P0}.** The small-rank hypothesis of
    `goldbach_of_walls_prev` is discharged by `small_ranks_clear`; `WallIAt {P0}` and
    `WallIIAt {P0}` remain open hypotheses. -/
theorem goldbach_of_walls_{P0} (hI : WallIAt {P0}) (hII : WallIIAt {P0}) :
    ∀ N, 8 ≤ N → Even N → GoldbachAt N :=
  goldbach_of_walls_prev {P0} hI hII
    (fun P p N hP h5 hlt hprc _ => small_ranks_clear P p N hP h5 hlt hprc)

#print axioms small_ranks_clear
#print axioms goldbach_of_walls_{P0}

end WilliamsonMurII
""")
open(out,'w').write("\n".join(L))
print("ranks",ranks[0],"..",ranks[-1],"candidates",tot)
